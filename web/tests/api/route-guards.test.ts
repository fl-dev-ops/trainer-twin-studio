const root = resolve(import.meta.dir, "../../app/api");
function routes(directory: string): string[] {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? routes(join(directory, entry.name)) : entry.name === "route.ts" ? [join(directory, entry.name)] : []);
}
function methods(source: string): string[] {
  const ast = ts.createSourceFile("route.ts", source, ts.ScriptTarget.Latest, true);
  const names: string[] = [];
  for (const node of ast.statements) {
    if (ts.isExportDeclaration(node) && node.exportClause && ts.isNamedExports(node.exportClause)) names.push(...node.exportClause.elements.map((element) => element.name.text));
    if ((ts.isFunctionDeclaration(node) || ts.isVariableStatement(node)) && node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)) {
      if (ts.isFunctionDeclaration(node) && node.name) names.push(node.name.text);
      if (ts.isVariableStatement(node)) names.push(...node.declarationList.declarations.map((declaration) => declaration.name.getText(ast)));
    }
  }
  return names.filter((name) => /^(GET|POST|PATCH|PUT|DELETE|HEAD|OPTIONS)$/.test(name));
}
test("every API route method export has an explicitly reviewed guard classification", () => {
  const exports = routes(root).flatMap((file) => methods(readFileSync(file, "utf8")).map((method) => `${method} ${relative(root, file).replace(/\/route\.ts$/, "")}`));
  expect(exports.length).toBeGreaterThan(100);
  expect(exports.filter((key) => !classification[key])).toEqual([]);
  expect(Object.keys(classification).filter((key) => !exports.includes(key))).toEqual([]);
});
test("route inventory includes aliased and re-exported methods, not runtime/config exports", () => {
  expect(methods('export { handler as GET, handler as POST }; export { PATCH } from "./other"; export const runtime = "nodejs"; export async function DELETE() {} export const HEAD = handler, OPTIONS = handler;')).toEqual(["GET", "POST", "PATCH", "DELETE", "HEAD", "OPTIONS"]);
});
